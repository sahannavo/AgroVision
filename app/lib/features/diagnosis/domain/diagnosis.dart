import 'package:flutter/foundation.dart';
import 'disease_class.dart';

/// Synchronization state for diagnoses saved offline.
enum SyncStatus {
  synced,
  pending;

  String get displayName => this == SyncStatus.synced ? 'Synced' : 'Pending';
}

/// A candidate class match with associated probability.
@immutable
class TopMatch {
  final DiseaseClass diseaseClass;
  final double confidence;

  const TopMatch({
    required this.diseaseClass,
    required this.confidence,
  });

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is TopMatch &&
          runtimeType == other.runtimeType &&
          diseaseClass == other.diseaseClass &&
          confidence == other.confidence;

  @override
  int get hashCode => Object.hash(diseaseClass, confidence);

  @override
  String toString() => '${diseaseClass.displayName}: ${(confidence * 100).toStringAsFixed(1)}%';
}

/// Full diagnosis entity generated by on-device model inference or retrieved from history.
@immutable
class Diagnosis {
  final String id;
  final String userId;
  final String? cropId;
  final String cropType;
  final String imagePath;
  final DiseaseClass predictedClass;
  final double confidence;
  final List<TopMatch> topMatches;
  final double? latitude;
  final double? longitude;
  final DateTime diagnosedAt;
  final SyncStatus syncStatus;

  const Diagnosis({
    required this.id,
    required this.userId,
    this.cropId,
    required this.cropType,
    required this.imagePath,
    required this.predictedClass,
    required this.confidence,
    required this.topMatches,
    this.latitude,
    this.longitude,
    required this.diagnosedAt,
    this.syncStatus = SyncStatus.synced,
  });

  /// Associated educational and advisory metadata for this diagnosis.
  DiseaseInfo get diseaseInfo => DiseaseInfo.forClass(predictedClass);

  Diagnosis copyWith({
    String? id,
    String? userId,
    String? cropId,
    String? cropType,
    String? imagePath,
    DiseaseClass? predictedClass,
    double? confidence,
    List<TopMatch>? topMatches,
    double? latitude,
    double? longitude,
    DateTime? diagnosedAt,
    SyncStatus? syncStatus,
  }) {
    return Diagnosis(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      cropId: cropId ?? this.cropId,
      cropType: cropType ?? this.cropType,
      imagePath: imagePath ?? this.imagePath,
      predictedClass: predictedClass ?? this.predictedClass,
      confidence: confidence ?? this.confidence,
      topMatches: topMatches ?? this.topMatches,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      diagnosedAt: diagnosedAt ?? this.diagnosedAt,
      syncStatus: syncStatus ?? this.syncStatus,
    );
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is Diagnosis &&
          runtimeType == other.runtimeType &&
          id == other.id &&
          userId == other.userId &&
          cropId == other.cropId &&
          cropType == other.cropType &&
          imagePath == other.imagePath &&
          predictedClass == other.predictedClass &&
          confidence == other.confidence &&
          listEquals(topMatches, other.topMatches) &&
          latitude == other.latitude &&
          longitude == other.longitude &&
          diagnosedAt == other.diagnosedAt &&
          syncStatus == other.syncStatus;

  @override
  int get hashCode => Object.hash(
        id,
        userId,
        cropId,
        cropType,
        imagePath,
        predictedClass,
        confidence,
        Object.hashAll(topMatches),
        latitude,
        longitude,
        diagnosedAt,
        syncStatus,
      );

  @override
  String toString() =>
      'Diagnosis(id: $id, crop: $cropType, class: ${predictedClass.displayName}, conf: ${(confidence * 100).toStringAsFixed(1)}%, sync: $syncStatus)';
}

