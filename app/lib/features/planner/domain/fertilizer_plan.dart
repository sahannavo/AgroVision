library;

/// Domain entities and data structures for fertilizer scheduling and weekly irrigation summaries.

/// Representation of a single scheduled fertilizer application.
class FertilizerScheduleItem {
  final String fertilizerType;
  final double amountGramsPerPlant;
  final int intervalDays;
  final String applicationMethod;
  final String tag;

  const FertilizerScheduleItem({
    required this.fertilizerType,
    required this.amountGramsPerPlant,
    required this.intervalDays,
    required this.applicationMethod,
    this.tag = 'Top-dress',
  });

  Map<String, dynamic> toMap() {
    return {
      'fertilizerType': fertilizerType,
      'amountGramsPerPlant': amountGramsPerPlant,
      'intervalDays': intervalDays,
      'applicationMethod': applicationMethod,
      'tag': tag,
    };
  }

  factory FertilizerScheduleItem.fromMap(Map<String, dynamic> map) {
    return FertilizerScheduleItem(
      fertilizerType: map['fertilizerType'] as String? ?? 'NPK 12–12–17',
      amountGramsPerPlant: (map['amountGramsPerPlant'] as num?)?.toDouble() ?? 20.0,
      intervalDays: (map['intervalDays'] as num?)?.toInt() ?? 14,
      applicationMethod: map['applicationMethod'] as String? ?? 'Apply along drip perimeter',
      tag: map['tag'] as String? ?? 'Top-dress',
    );
  }
}

/// Aggregated weekly metrics generated by the planner engine.
class WeeklyPlannerSummary {
  final double totalWaterLitresPerSqm;
  final int activeWateringDaysCount;
  final String nextFertilizerDate;
  final String fertilizerProduct;

  const WeeklyPlannerSummary({
    required this.totalWaterLitresPerSqm,
    required this.activeWateringDaysCount,
    required this.nextFertilizerDate,
    required this.fertilizerProduct,
  });

  Map<String, dynamic> toMap() {
    return {
      'totalWaterLitresPerSqm': totalWaterLitresPerSqm,
      'activeWateringDaysCount': activeWateringDaysCount,
      'nextFertilizerDate': nextFertilizerDate,
      'fertilizerProduct': fertilizerProduct,
    };
  }

  factory WeeklyPlannerSummary.fromMap(Map<String, dynamic> map) {
    return WeeklyPlannerSummary(
      totalWaterLitresPerSqm: (map['totalWaterLitresPerSqm'] as num?)?.toDouble() ?? 28.0,
      activeWateringDaysCount: (map['activeWateringDaysCount'] as num?)?.toInt() ?? 5,
      nextFertilizerDate: map['nextFertilizerDate'] as String? ?? 'Fri 16 Oct',
      fertilizerProduct: map['fertilizerProduct'] as String? ?? 'NPK 12–12–17 top-dress',
    );
  }
}

/// Computed irrigation and fertilizer schedule for a single day.
class EngineDaySchedule {
  final DateTime date;
  final String dateLabel;
  final double waterAmountLitresPerSqm;
  final String preferredTimeOfDay;
  final bool isSkipped;
  final String? skipReason;
  final String? skipDetail;
  final FertilizerScheduleItem? fertilizer;
  final String status;

  const EngineDaySchedule({
    required this.date,
    required this.dateLabel,
    required this.waterAmountLitresPerSqm,
    required this.preferredTimeOfDay,
    this.isSkipped = false,
    this.skipReason,
    this.skipDetail,
    this.fertilizer,
    required this.status,
  });

  Map<String, dynamic> toMap() {
    return {
      'date': date.toIso8601String(),
      'dateLabel': dateLabel,
      'waterAmountLitresPerSqm': waterAmountLitresPerSqm,
      'preferredTimeOfDay': preferredTimeOfDay,
      'isSkipped': isSkipped,
      'skipReason': skipReason,
      'skipDetail': skipDetail,
      'fertilizer': fertilizer?.toMap(),
      'status': status,
    };
  }
}

/// The complete 7-day output plan produced by the planner engine.
class FullIrrigationPlan {
  final String cropId;
  final String growthStage;
  final WeeklyPlannerSummary summary;
  final List<EngineDaySchedule> daySchedules;
  final DateTime generatedAt;
  final bool isWeatherCached;

  const FullIrrigationPlan({
    required this.cropId,
    required this.growthStage,
    required this.summary,
    required this.daySchedules,
    required this.generatedAt,
    this.isWeatherCached = false,
  });

  Map<String, dynamic> toMap() {
    return {
      'cropId': cropId,
      'growthStage': growthStage,
      'summary': summary.toMap(),
      'daySchedules': daySchedules.map((s) => s.toMap()).toList(),
      'generatedAt': generatedAt.toIso8601String(),
      'isWeatherCached': isWeatherCached,
    };
  }
}
